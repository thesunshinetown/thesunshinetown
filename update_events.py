"""
update_events.py

Builds events.json for the Sunshine Town site from three sources:

  1. The Town of Newport, NH's official iCal calendar (mostly meetings).
     Recurring meetings are expanded automatically.
  2. The Friday Farmers Market on the Town Common, generated by date rule
     (Fridays, 3-6 PM, from the Friday before Memorial Day through the Friday
     before Columbus Day). Adjust MARKET_* below if the market changes.
  3. manual_events.json -- events you add by hand. Anything in that file is
     merged in on every run, so hand-added events are never overwritten.

Runs daily from the GitHub Actions workflow.

Setup:
    pip install -r requirements.txt

Usage:
    python update_events.py
"""

import json
import datetime
import os
from zoneinfo import ZoneInfo

import requests
from icalendar import Calendar

try:
    import recurring_ical_events
except ImportError:  # falls back to one-off events only
    recurring_ical_events = None

TZ = ZoneInfo("America/New_York")

FEEDS = [
    "https://www.newportnh.gov/calendar/ical/export.ics",
]

LOOKAHEAD_DAYS = 60
MAX_EVENTS = 25

MANUAL_FILE = "manual_events.json"

# Farmers Market: Fridays 3-6 PM on the Town Common, from the Friday before
# Memorial Day to the Friday before Columbus Day (per the market's page).
MARKET_ENABLED = True
MARKET_TITLE = "Newport Farmers Market"
MARKET_TIME = "3:00 PM - 6:00 PM"
MARKET_LOCATION = "Newport Town Common"

CATEGORY_HINTS = {
    "selectmen": "Town Government",
    "selectboard": "Town Government",
    "planning board": "Town Government",
    "zoning": "Town Government",
    "zba": "Town Government",
    "conservation": "Town Government",
    "budget": "Town Government",
    "library": "Library",
    "recreation": "Recreation",
    "concert": "Music",
    "airport": "Town Government",
    "fire": "Town Government",
}


def guess_category(title):
    lowered = title.lower()
    for hint, category in CATEGORY_HINTS.items():
        if hint in lowered:
            return category
    return "Community"


def nth_weekday(year, month, weekday, n):
    """n-th (1-based) given weekday of a month. weekday: Mon=0 ... Sun=6."""
    first = datetime.date(year, month, 1)
    offset = (weekday - first.weekday()) % 7
    return first + datetime.timedelta(days=offset + 7 * (n - 1))


def last_weekday(year, month, weekday):
    if month == 12:
        nxt = datetime.date(year + 1, 1, 1)
    else:
        nxt = datetime.date(year, month + 1, 1)
    last = nxt - datetime.timedelta(days=1)
    return last - datetime.timedelta(days=(last.weekday() - weekday) % 7)


def market_season(year):
    memorial_day = last_weekday(year, 5, 0)          # last Monday of May
    columbus_day = nth_weekday(year, 10, 0, 2)       # second Monday of October
    start = memorial_day - datetime.timedelta(days=3)   # Friday before
    end = columbus_day - datetime.timedelta(days=3)     # Friday before
    return start, end


def market_events(today, cutoff):
    events = []
    for year in {today.year, cutoff.year}:
        start, end = market_season(year)
        day = start
        while day <= end:
            if today <= day <= cutoff:
                events.append({
                    "date": day.isoformat(),
                    "time": MARKET_TIME,
                    "title": MARKET_TITLE,
                    "location": MARKET_LOCATION,
                    "category": "Market",
                })
            day += datetime.timedelta(days=7)
    return events


def to_local_date_time(dt):
    """Return (date, time_string) for an iCal DTSTART/DTEND value."""
    if isinstance(dt, datetime.datetime):
        if dt.tzinfo is not None:
            dt = dt.astimezone(TZ)
        return dt.date(), dt.strftime("%I:%M %p").lstrip("0")
    return dt, "All day"


def ical_events(url, today, cutoff):
    resp = requests.get(url, timeout=30, headers={"User-Agent": "SunshineTownBot/1.0"})
    resp.raise_for_status()
    cal = Calendar.from_ical(resp.content)

    if recurring_ical_events is not None:
        components = recurring_ical_events.of(cal).between(today, cutoff + datetime.timedelta(days=1))
    else:
        components = cal.walk("VEVENT")

    events = []
    for comp in components:
        dtstart = comp.get("dtstart")
        if not dtstart:
            continue
        event_date, time_str = to_local_date_time(dtstart.dt)
        if event_date < today or event_date > cutoff:
            continue
        title = str(comp.get("summary", "Untitled event")).strip()
        location = str(comp.get("location", "") or "").strip() or "Newport, NH"
        events.append({
            "date": event_date.isoformat(),
            "time": time_str,
            "title": title,
            "location": location,
            "category": guess_category(title),
        })
    return events


def manual_events(today, cutoff):
    if not os.path.exists(MANUAL_FILE):
        return []
    try:
        with open(MANUAL_FILE) as f:
            data = json.load(f)
    except Exception as e:
        print(f"Could not read {MANUAL_FILE}: {e}")
        return []
    out = []
    for ev in data.get("events", []):
        try:
            d = datetime.date.fromisoformat(ev["date"])
        except Exception:
            print(f"Skipping manual event with a bad date: {ev}")
            continue
        if today <= d <= cutoff and ev.get("title"):
            out.append({
                "date": d.isoformat(),
                "time": ev.get("time", ""),
                "title": ev["title"],
                "location": ev.get("location", ""),
                "category": ev.get("category", "Community"),
            })
    return out


def main():
    today = datetime.datetime.now(TZ).date()
    cutoff = today + datetime.timedelta(days=LOOKAHEAD_DAYS)

    all_events = []

    for url in FEEDS:
        try:
            found = ical_events(url, today, cutoff)
            print(f"{url}: {len(found)} events")
            all_events.extend(found)
        except Exception as e:
            print(f"Skipped {url}: {e}")

    if MARKET_ENABLED:
        market = market_events(today, cutoff)
        print(f"Farmers Market: {len(market)} dates in range")
        all_events.extend(market)

    manual = manual_events(today, cutoff)
    print(f"Manual events: {len(manual)}")
    all_events.extend(manual)

    # De-duplicate on date + title, then sort.
    seen = set()
    unique = []
    for ev in all_events:
        key = (ev["date"], ev["title"].lower())
        if key in seen:
            continue
        seen.add(key)
        unique.append(ev)
    unique.sort(key=lambda e: (e["date"], e["time"]))
    unique = unique[:MAX_EVENTS]

    output = {
        "updated": today.isoformat(),
        "events": unique if unique else [
            {
                "date": today.isoformat(),
                "time": "",
                "title": "No upcoming events found",
                "location": "",
                "category": "system",
            }
        ],
    }

    with open("events.json", "w") as f:
        json.dump(output, f, indent=2)

    print(f"Wrote {len(unique)} events to events.json")


if __name__ == "__main__":
    main()
